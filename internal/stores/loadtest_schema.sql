CREATE TABLE IF NOT EXISTS load_tests (
    id                TEXT PRIMARY KEY,
    target_url        TEXT NOT NULL,
    method            TEXT NOT NULL,
    duration_seconds  INTEGER NOT NULL,
    requests_per_sec  INTEGER NOT NULL,
    concurrency       INTEGER NOT NULL,
    status            TEXT NOT NULL,
    error_message     TEXT NOT NULL DEFAULT '',
    created_at        TEXT NOT NULL,
    started_at        TEXT NOT NULL DEFAULT '',
    finished_at       TEXT NOT NULL DEFAULT '',
    total_requests    INTEGER NOT NULL DEFAULT 0,
    successful        INTEGER NOT NULL DEFAULT 0,
    failed            INTEGER NOT NULL DEFAULT 0,
    error_rate        REAL NOT NULL DEFAULT 0,
    rps_achieved      REAL NOT NULL DEFAULT 0,
    min_ms            REAL NOT NULL DEFAULT 0,
    max_ms            REAL NOT NULL DEFAULT 0,
    mean_ms           REAL NOT NULL DEFAULT 0,
    p50_ms            REAL NOT NULL DEFAULT 0,
    p90_ms            REAL NOT NULL DEFAULT 0,
    p95_ms            REAL NOT NULL DEFAULT 0,
    p99_ms            REAL NOT NULL DEFAULT 0,
    status_breakdown  TEXT NOT NULL DEFAULT '{}',
    error_breakdown   TEXT NOT NULL DEFAULT '{}'
);